"""Checks on the synthetic sample data in data/sample/.

The two sample PDFs are generated by scripts/data/make_sample_pdfs.py (standard library only).
If someone edits the generator or the PDFs, these tests make sure the committed files still
match the generator byte for byte, so the data stays explainable and reproducible.
"""

import importlib.util
import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SAMPLE = REPO_ROOT / "data" / "sample"


def _load_generator():
    path = REPO_ROOT / "scripts" / "data" / "make_sample_pdfs.py"
    spec = importlib.util.spec_from_file_location("make_sample_pdfs", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_sample_pdfs_match_their_generator() -> None:
    generator = _load_generator()
    for name, build in generator.BUILDERS.items():
        committed = (SAMPLE / "acme-handbook" / name).read_bytes()
        assert committed == build(), (
            f"{name} differs from scripts/data/make_sample_pdfs.py. "
            "If the change is intended, run the script and commit the result. "
            "If Git rewrote the file, check that .gitattributes marks *.pdf as binary."
        )


def test_permission_export_is_well_formed() -> None:
    export = json.loads((SAMPLE / "access-control.json").read_text(encoding="utf-8"))
    permissions = export["permissions"]
    for path, groups in permissions.items():
        assert (SAMPLE / path).is_file(), f"permission entry for a missing file: {path}"
        assert groups and all(isinstance(g, str) and g for g in groups), path
    # Deliberate gap used by Day 02 to demonstrate fail-closed ingestion.
    assert "acme-handbook/draft-reorg-announcement.txt" not in permissions
